//! Arbitrary models: an OBJ that is not a cube, drawn with a texture.
//!
//! The rest of the 3D suite uses the procedural primitives, which makes it possible to
//! believe the engine only draws cubes and spheres. It does not: `load_obj_mesh` uploads
//! any triangle mesh, and this test generates a torus knot at runtime — thousands of
//! vertices, curved surface, UVs — so nothing about the result can come from a built-in
//! primitive.
//!
//! The OBJ is written to a temporary directory instead of committed: a binary asset would
//! be a file nobody can read in a diff, and generating it keeps the test independent of
//! whatever a reviewer has in `assets/`.

mod common;

use std::fmt::Write as _;
use std::path::PathBuf;
use std::sync::MutexGuard;

use giochi_engine::platform::sdl::Platform;
use giochi_engine::platform::window::{Window, WindowConfig};
use giochi_engine_3d::context::{self, GlesVersion};
use giochi_engine_3d::math3d::{Camera3D, Color3D, Transform3D, Vec3};
use giochi_engine_3d::mesh::{load_obj, Vertex};
use giochi_engine_3d::shader::BuiltinShader;
use giochi_engine_3d::RenderContext3D;

const SIZE: u32 = 200;

fn headless() -> Option<(MutexGuard<'static, ()>, Platform, Window, RenderContext3D)> {
    let guard = common::platform_guard();
    std::env::set_var("SDL_VIDEODRIVER", "offscreen");
    let platform = Platform::new().ok()?;
    context::configure_attributes(&platform, GlesVersion::Gles2).ok()?;
    let window = Window::new_opengl(&platform, WindowConfig::new(SIZE, SIZE), "obj").ok()?;
    let render = RenderContext3D::new(context::create(&window).ok()?);
    Some((guard, platform, window, render))
}

/// Writes a `(p, q)` torus knot as a Wavefront OBJ and returns its path.
///
/// The knot is chosen because it is unmistakably not a cube or a sphere: a closed curve
/// with a tube swept along it, so its silhouette and its normals vary in every direction.
fn torus_knot_obj(name: &str, rings: usize, sides: usize) -> PathBuf {
    const P: f32 = 2.0;
    const Q: f32 = 3.0;
    const RADIUS: f32 = 1.0;
    /// Distance from the knot's axis, which is what lifts the centre line off the XY
    /// plane instead of tracing a plain torus.
    const WIND: f32 = 0.45;
    const TUBE: f32 = 0.10;

    // (p, q) torus knot centre line: it winds `Q` times around the `P`-fold loop, so the
    // silhouette is a knot and not a ring.
    let centre_at = |t: f32| {
        [
            (RADIUS + WIND * (Q * t).cos()) * (P * t).cos(),
            (RADIUS + WIND * (Q * t).cos()) * (P * t).sin(),
            WIND * (Q * t).sin(),
        ]
    };

    let mut text = String::from("# generated by tests/obj_models.rs\n");

    for i in 0..rings {
        let t = std::f32::consts::TAU * i as f32 / rings as f32;
        let centre = centre_at(t);
        let before = centre_at(t - 0.001);
        let after = centre_at(t + 0.001);

        // Tangent from a finite difference of the centre line, then a frame around it.
        let tangent = normalize([
            after[0] - before[0],
            after[1] - before[1],
            after[2] - before[2],
        ]);
        let reference = if tangent[2].abs() < 0.9 {
            [0.0, 0.0, 1.0]
        } else {
            [1.0, 0.0, 0.0]
        };
        let binormal = normalize(cross(tangent, reference));
        let normal_axis = cross(binormal, tangent);

        for j in 0..sides {
            let u = std::f32::consts::TAU * j as f32 / sides as f32;
            // Outward direction of the tube at this angle; it is also the surface normal.
            let outward = normalize([
                normal_axis[0] * u.cos() + binormal[0] * u.sin(),
                normal_axis[1] * u.cos() + binormal[1] * u.sin(),
                normal_axis[2] * u.cos() + binormal[2] * u.sin(),
            ]);
            let position = [
                centre[0] + outward[0] * TUBE,
                centre[1] + outward[1] * TUBE,
                centre[2] + outward[2] * TUBE,
            ];
            writeln!(text, "v {} {} {}", position[0], position[1], position[2]).unwrap();
            writeln!(text, "vn {} {} {}", outward[0], outward[1], outward[2]).unwrap();
            writeln!(
                text,
                "vt {} {}",
                i as f32 / rings as f32,
                j as f32 / sides as f32
            )
            .unwrap();
        }
    }

    for i in 0..rings {
        for j in 0..sides {
            let a = i * sides + j;
            let b = ((i + 1) % rings) * sides + j;
            let c = ((i + 1) % rings) * sides + (j + 1) % sides;
            let d = i * sides + (j + 1) % sides;
            for corner in [[a, b, c], [a, c, d]] {
                let [x, y, z] = corner.map(|index| index + 1);
                writeln!(text, "f {x}/{x}/{x} {y}/{y}/{y} {z}/{z}/{z}").unwrap();
            }
        }
    }

    let path = std::env::temp_dir().join(name);
    std::fs::write(&path, text).expect("write the generated OBJ");
    path
}

fn cross(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

fn normalize(v: [f32; 3]) -> [f32; 3] {
    let length = (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt();
    [v[0] / length, v[1] / length, v[2] / length]
}

fn split_texture(render: &mut RenderContext3D) -> u64 {
    const W: u32 = 16;
    const H: u32 = 16;
    let mut pixels = vec![0u8; (W * H * 4) as usize];
    for y in 0..H {
        for x in 0..W {
            let offset = ((y * W + x) * 4) as usize;
            let colour = if x < W / 2 { [255, 0, 0] } else { [0, 0, 255] };
            pixels[offset..offset + 4].copy_from_slice(&[colour[0], colour[1], colour[2], 255]);
        }
    }
    render
        .create_texture_from_rgba(W, H, &pixels)
        .expect("procedural texture")
}

/// Pixels that are not the clear colour.
fn covered(pixels: &[u8]) -> usize {
    pixels
        .chunks_exact(4)
        .filter(|pixel| pixel[0] > 8 || pixel[1] > 8 || pixel[2] > 8)
        .count()
}

#[test]
fn an_obj_that_is_not_a_primitive_loads_with_uvs_and_normals() {
    let path = torus_knot_obj("giochi-torus-loader.obj", 48, 16);
    let (vertices, indices) = load_obj(&path).expect("the generated OBJ parses");
    let _ = std::fs::remove_file(&path);

    // 48 rings * 16 sides, and two triangles per quad.
    assert_eq!(vertices.len(), 48 * 16, "vertex count");
    assert_eq!(indices.len(), 48 * 16 * 6, "index count");
    assert!(
        vertices.len() > 500,
        "the point of this test is a mesh no primitive would produce"
    );

    for vertex in &vertices {
        let [x, y, z] = vertex.normal;
        let length = (x * x + y * y + z * z).sqrt();
        assert!(
            (length - 1.0).abs() < 1e-3,
            "normal must be unit, got {vertex:?}"
        );
    }
    assert!(
        vertices.iter().any(|vertex| vertex.uv != [0.0, 0.0]),
        "the OBJ has vt records, so the loader must keep them"
    );
    assert!(
        indices
            .iter()
            .all(|index| (*index as usize) < vertices.len()),
        "every index must be in range"
    );
}

#[test]
fn an_obj_model_draws_textured_with_its_own_geometry() {
    let Some((_guard, _platform, window, mut render)) = headless() else {
        eprintln!("skipped: no OpenGL ES driver available");
        return;
    };

    let path = torus_knot_obj("giochi-torus-draw.obj", 64, 20);
    let mesh = render.load_obj_mesh(&path).expect("upload the model");
    let _ = std::fs::remove_file(&path);

    let texture = split_texture(&mut render);
    let shader = render
        .create_builtin_shader(BuiltinShader::Textured)
        .expect("textured shader");

    let camera =
        Camera3D::from_parts(Vec3::new(0.0, 0.0, 4.0), Vec3::ZERO, Vec3::UP).with_aspect(1.0);

    render.set_clear_color(Color3D::BLACK);
    render.begin_frame(&window);
    assert!(render
        .draw_mesh_textured(
            mesh,
            shader,
            texture,
            &Transform3D::IDENTITY,
            &camera,
            Color3D::WHITE,
        )
        .expect("draw"));
    let error = render.take_gl_error();
    assert_eq!(error, 0, "GL error 0x{error:04x}");

    let pixels = render.read_pixels(SIZE, SIZE).expect("read back");
    let lit = covered(&pixels);
    // The knot occupies a ring-shaped band, not a solid square: it must cover a real
    // part of the frame without filling it (which is what a broken camera would do).
    assert!(
        lit > SIZE as usize * SIZE as usize / 20,
        "the model covered only {lit} pixels"
    );
    assert!(
        lit < SIZE as usize * SIZE as usize * 8 / 10,
        "{lit} pixels is most of the frame; the camera framing is wrong"
    );

    assert!(render.destroy_mesh(mesh));
    assert!(render.destroy_texture(texture));
    assert!(render.destroy_shader(shader));
}

#[test]
fn a_mesh_with_zero_normals_is_lit_instead_of_undefined() {
    // `normalize(vec3(0.0))` is undefined in GLSL ES 1.00. On the AMD driver measured here
    // it returns zero, which lands on the ambient-only term (89/255); another driver can
    // produce NaN and a black surface. Neither is what the caller asked for, so
    // `create_mesh` derives the normal from the triangles.
    //
    // The flat shader hardcodes its light at normalize(0.4, 0.9, 0.3), so the quad is
    // built facing exactly that direction: with a derived normal it is fully lit
    // (~255), while an ambient-only surface would be 89. That gap is what makes this
    // test able to tell the two apart — a plain grey quad would pass either way.
    let Some((_guard, _platform, window, mut render)) = headless() else {
        eprintln!("skipped: no OpenGL ES driver available");
        return;
    };

    let n = normalize([0.4, 0.9, 0.3]);
    let tangent = normalize(cross(n, [0.0, 0.0, 1.0]));
    let bitangent = cross(n, tangent);

    let corner = |scale: f32, ti: f32, bi: f32| {
        [
            (tangent[0] * ti + bitangent[0] * bi) * scale,
            (tangent[1] * ti + bitangent[1] * bi) * scale,
            (tangent[2] * ti + bitangent[2] * bi) * scale,
        ]
    };

    // Wound so `cross(p1 - p0, p2 - p0)` points along `n`; the derived normal then faces
    // the hardcoded light.
    let vertices = [
        Vertex::new(corner(1.0, -1.0, -1.0), [0.0; 3], [0.0, 1.0]),
        Vertex::new(corner(1.0, 1.0, -1.0), [0.0; 3], [1.0, 1.0]),
        Vertex::new(corner(1.0, 1.0, 1.0), [0.0; 3], [1.0, 0.0]),
        Vertex::new(corner(1.0, -1.0, 1.0), [0.0; 3], [0.0, 0.0]),
    ];
    let indices = [0u32, 1, 2, 0, 2, 3];

    let mesh = render.create_mesh(&vertices, &indices).expect("mesh");
    let shader = render
        .create_builtin_shader(BuiltinShader::Flat)
        .expect("flat shader");
    let camera =
        Camera3D::from_parts(Vec3::new(0.0, 0.0, 3.0), Vec3::ZERO, Vec3::UP).with_aspect(1.0);

    render.set_clear_color(Color3D::BLACK);
    render.begin_frame(&window);
    render
        .draw_mesh_colored(
            mesh,
            shader,
            &Transform3D::IDENTITY,
            &camera,
            Color3D::WHITE,
        )
        .expect("draw");

    let pixels = render.read_pixels(SIZE, SIZE).expect("read back");
    let centre = ((SIZE / 2) * SIZE + SIZE / 2) as usize * 4;
    let [r, g, b, a] = [
        pixels[centre],
        pixels[centre + 1],
        pixels[centre + 2],
        pixels[centre + 3],
    ];
    assert_eq!(a, 255, "the quad must be opaque at the centre");
    assert!(
        r > 200,
        "a derived normal facing the light must be near-white, got ({r}, {g}, {b}); \
         ~89 means the zero normal reached the shader as a zero vector"
    );

    assert!(render.destroy_mesh(mesh));
    assert!(render.destroy_shader(shader));
}

#[test]
fn a_multi_object_obj_is_one_drawable_mesh() {
    // A model exported from Blender often carries several `o` records. The loader merges
    // them, so one handle draws the whole character instead of just the first part.
    let path = std::env::temp_dir().join("giochi-two-parts.obj");
    std::fs::write(
        &path,
        "\
o body
v 0 0 0
v 1 0 0
v 0 1 0
f 1 2 3
o wing
v 0 0 1
v 1 0 1
v 0 1 1
f 4 5 6
",
    )
    .expect("write");

    let (vertices, indices) = load_obj(&path).expect("both parts parse");
    let _ = std::fs::remove_file(&path);

    assert_eq!(vertices.len(), 6);
    assert_eq!(
        indices,
        vec![0, 1, 2, 3, 4, 5],
        "second part's indices must be rebased, not aliasing the first"
    );
}
